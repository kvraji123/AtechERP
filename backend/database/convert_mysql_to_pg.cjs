const fs = require('fs');
const src = fs.readFileSync('backend/database/atech-production-complete.sql','utf8');
let s = src;
s = s.replace(/CREATE DATABASE IF NOT EXISTS[\s\S]*?;\s*USE `atech_erp`;\s*/i, '');
s = s.replace(/^\s*USE `[^`]+`;\s*$/gim, '');
s = s.replace(/^\s*SET (NAMES|time_zone|FOREIGN_KEY_CHECKS)[^;]*;\s*$/gim, '');
s = s.replace(/`([^`]+)`/g, '$1');
s = s.replace(/\s+ENGINE=InnoDB\s+DEFAULT CHARSET=utf8mb4\s+COLLATE=utf8mb4_unicode_ci/g, '');
s = s.replace(/\bUNSIGNED\b/g, '');
s = s.replace(/AUTO_INCREMENT/g, 'GENERATED BY DEFAULT AS IDENTITY');
s = s.replace(/TINYINT\(1\)/g, 'BOOLEAN');
s = s.replace(/CURRENT_TIMESTAMP\s+ON UPDATE\s+CURRENT_TIMESTAMP/g, 'CURRENT_TIMESTAMP');
s = s.replace(/\s+AFTER\s+[A-Za-z0-9_]+/g, '');
s = s.replace(/ALTER TABLE[\s\S]*?MODIFY COLUMN[\s\S]*?;\s*/gi, '');
s = s.replace(/DATE_ADD\(CURRENT_DATE,\s*INTERVAL\s+(\d+)\s+DAY\)/gi, "(CURRENT_DATE + INTERVAL '$1 days')");
s = s.replace(/ON DUPLICATE KEY UPDATE[\s\S]*?;\s*/gi, ';\n');
function replaceEnums(text) {
  let out='', i=0;
  while (i<text.length) {
    const j=text.indexOf('ENUM(', i);
    if (j<0) { out += text.slice(i); break; }
    out += text.slice(i,j);
    let k=j+5, depth=1;
    while (k<text.length && depth) { if (text[k]==='(') depth++; else if (text[k]===')') depth--; k++; }
    out += 'VARCHAR(40)'; i=k;
  }
  return out;
}
s = replaceEnums(s);
const demo = fs.readFileSync('backend/database/atech-postgresql-purchase-demo.sql','utf8');
fs.writeFileSync('backend/database/atech-postgresql-full-replica.sql', `-- A TECH AUTOMATION ERP - PostgreSQL full replica\n-- Converted from the current MySQL install schema. Separate database file;\n-- it does not modify the existing MySQL database. PostgreSQL 14+.\n\n${s}\n\n-- PostgreSQL Purchase/RFQ demo data\n${demo}\n`);
