import { Router } from "express";
import { asyncHandler } from "../../utils/asyncHandler.js";
import { requirePermission } from "../../shared/middleware/requirePermission.js";
import * as controller from "./purchase-order-approval.controller.js";
const router = Router();
router.get("/", requirePermission("PO_APPROVE"), asyncHandler(controller.list));
router.get("/summary", requirePermission("PO_APPROVE"), asyncHandler(controller.summary));
router.get("/:id", requirePermission("PO_APPROVE"), asyncHandler(controller.get));
router.post("/:id/:action(approve|return|reject)", requirePermission("PO_APPROVE"), asyncHandler(controller.decide));
export default router;
