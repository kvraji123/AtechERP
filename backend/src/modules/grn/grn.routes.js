import { Router } from "express";
import { uploadSingle } from "../../middleware/upload.js";
import { asyncHandler } from "../../utils/asyncHandler.js";
import { requirePermission } from "../../shared/middleware/requirePermission.js";
import * as controller from "./grn.controller.js";
const router = Router();
router.get("/suppliers", requirePermission("GRN_POST"), asyncHandler(controller.listSupplierOptions));
router.get("/", requirePermission("GRN_POST"), asyncHandler(controller.list));
router.get("/summary", requirePermission("GRN_POST"), asyncHandler(controller.summary));
router.get("/:id", requirePermission("GRN_POST"), asyncHandler(controller.get));
router.get("/:id/rejections", requirePermission("GRN_POST"), asyncHandler(controller.listRejections));
router.post("/:id/items/:grnItemId/rejection-attachments", requirePermission("GRN_POST"), (req,res,next) => { req.params.moduleName="grn-rejections"; uploadSingle(req,res,next); }, asyncHandler(controller.uploadRejectionAttachment));
router.delete("/:id/items/:grnItemId/rejection-attachments/:attachmentId", requirePermission("GRN_POST"), asyncHandler(controller.deleteRejectionAttachment));
router.post("/", requirePermission("GRN_POST"), asyncHandler(controller.create));
router.put("/:id", requirePermission("GRN_POST"), asyncHandler(controller.update));
router.post("/:id/inspect", requirePermission("GRN_POST"), asyncHandler(controller.inspect));
router.post("/:id/post", requirePermission("GRN_POST"), asyncHandler(controller.post));
router.post("/:id/approve-purchase", requirePermission("PO_APPROVE"), asyncHandler(controller.approvePurchase));
export default router;
